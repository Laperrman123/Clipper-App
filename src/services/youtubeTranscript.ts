const ID_PATTERNS = [
  /[?&]v=([\w-]{11})/,
  /youtu\.be\/([\w-]{11})/,
  /\/shorts\/([\w-]{11})/,
  /\/live\/([\w-]{11})/,
  /\/embed\/([\w-]{11})/,
];

export function getYouTubeVideoId(url: string): string | null {
  for (const pattern of ID_PATTERNS) {
    const match = url.match(pattern);
    if (match) return match[1];
  }
  return null;
}

export async function fetchYouTubeTranscript(
  url: string
): Promise<YouTubeTranscript | null> {
  const videoId = getYouTubeVideoId(url);
  if (!videoId) return null;

  for (const client of CLIENTS) {
    try {
      const { tracks, durationSec: playerDurationSec } = await fetchCaptionTracks(
        videoId,
        client
      );
      const track = pickTrack(tracks);
      if (!track) continue;

      const parsed = await fetchJson3(track.baseUrl);
      const segments = parsed.segments;
      if (segments.length === 0) continue;

      return {
        segments,
        // Ambil yang terbesar: durasi video dari player lebih andal daripada
        // akhir subtitle, yang bisa berhenti sebelum outro/musik penutup.
        durationSec: Math.max(parsed.durationSec, playerDurationSec),
        languageCode: track.languageCode,
        autoGenerated: Boolean(track.kind === 'asr'),
      };
    } catch {
      // Coba klien berikutnya.
    }
  }

  return null;
}

interface CaptionTrack {
  baseUrl: string;
  languageCode: string;
  name?: string;
  kind?: string;
}

/** Urutan bahasa: manual dulu (lebih akurat), lalu bahasa yang dipakai user. */
const LANGUAGE_PRIORITY = ['id', 'in', 'en', 'en-US', 'en-GB'];

async function fetchCaptionTracks(
  videoId: string,
  client: (typeof CLIENTS)[number]
): Promise<{ tracks: CaptionTrack[]; durationSec: number }> {
  const body = {
    context: {
      client: {
        clientName: client.name,
        clientVersion: client.version,
        hl: 'id',
        gl: 'ID',
        ...client.extra,
      },
    },
    videoId,
    contentCheckOk: true,
    racyCheckOk: true,
  };

  const json = await fetchJson(PLAYER_URL, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  });

  const tracks =
    json?.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];

  // Durasi asli video — dipakai supaya klip di ujung video tidak terpotong
  // hanya karena subtitle berhenti lebih awal.
  const lengthSec = Number(json?.videoDetails?.lengthSeconds);

  return {
    tracks: Array.isArray(tracks)
      ? tracks.filter((t: CaptionTrack) => typeof t?.baseUrl === 'string')
      : [],
    durationSec: Number.isFinite(lengthSec) && lengthSec > 0 ? lengthSec : 0,
  };
}

function pickTrack(tracks: CaptionTrack[]): CaptionTrack | null {
  if (tracks.length === 0) return null;

  // Manual (kind kosong) selalu lebih akurat daripada ASR otomatis.
  const manual = tracks.filter((t) => t.kind !== 'asr');
  const pool = manual.length > 0 ? manual : tracks;

  for (const lang of LANGUAGE_PRIORITY) {
    const hit = pool.find((t) => t.languageCode === lang);
    if (hit) return hit;
  }

  return pool[0];
}

/**
 * Format json3 dipakai karena sudah menyediakan tStartMs dan dDurationMs
 * per baris — tidak perlu menebak dari format lain.
 */
async function fetchJson3(baseUrl: string): Promise<{
  segments: TranscriptSegment[];
  durationSec: number;
}> {
  const url = baseUrl.includes('fmt=')
    ? baseUrl.replace(/fmt=[^&]+/, 'fmt=json3')
    : `${baseUrl}&fmt=json3`;

  const json = await fetchJson(url, { method: 'GET' });
  const events = Array.isArray(json?.events) ? json.events : [];

  const segments: TranscriptSegment[] = [];
  let prevNormalized = '';

  for (const event of events) {
    const segs = Array.isArray(event?.segs) ? event.segs : [];
    if (segs.length === 0) continue;

    const text = segs
      .map((s: { utf8?: string }) => s?.utf8 ?? '')
      .join('')
      .replace(/\s+/g, ' ')
      .trim();

    if (!isSpeakable(text)) continue;

    // ASR kadang mengulang baris yang sama persis berturut-turut (artefak
    // jendela geser). Kalau dibiarkan, chunk jadi menggelembung dan waktu
    // terasa tidak sinkron dengan audio.
    const normalized = text.toLowerCase().replace(/\s+/g, ' ').trim();
    if (normalized === prevNormalized) continue;
    prevNormalized = normalized;

    const startMs = Number(event.tStartMs);
    const durationMs = Number(event.dDurationMs);
    if (!Number.isFinite(startMs)) continue;

    segments.push({
      startMs,
      endMs: startMs + (Number.isFinite(durationMs) ? durationMs : 0),
      text,
    });
  }

  segments.sort((a, b) => a.startMs - b.startMs);

  const last = segments[segments.length - 1];
  return {
    segments,
    durationSec: last ? Math.ceil(last.endMs / 1000) : 0,
  };
}

/** Buang baris yang isinya cuma anotasi non-suara. */
function isSpeakable(text: string): boolean {
  if (text.length < 2) return false;
  // [Musik], (tawa), [Applause], "*", dan sejenisnya.
  const cleaned = text.replace(/[[(].*?[\])]/g, '').trim();
  if (cleaned.length < 2) return false;
  // Baris yang isinya cuma tanda baca ("..." atau "-") tidak dianggap ucapan.
  // Dedup baris berulang ditangani di fetchJson3 karena butuh konteks baris
  // sebelumnya.
  return !/^[\s\W]+$/.test(cleaned);
}

async function fetchJson(url: string, init: RequestInit): Promise<any> {
  const res = await withTimeout(fetch(url, init), REQUEST_TIMEOUT_MS);
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const text = await res.text();
  return text ? JSON.parse(text) : {};
}

/** RN tidak selalu punya AbortController, jadi pakai timeout manual. */
function withTimeout<T>(promise: Promise<T>, ms: number): Promise<T> {
  return new Promise<T>((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error('timeout')), ms);
    promise.then(
      (value) => {
        clearTimeout(timer);
        resolve(value);
      },
      (error) => {
        clearTimeout(timer);
        reject(error);
      }
    );
  });
}