/**
 * Ambil transkrip (subtitle) bawaan YouTube.
 *
 * Kenapa ini akurat: cap waktu subtitle YouTube dihasilkan dari ASR atas
 * audio yang sama persis dengan file videonya, jadi tidak ada "persepsi model"
 * yang bisa meleset. Bandingkan dengan meminta Gemini mendengarkan videonya
 * sendiri, di situ cap waktunya perkiraan model.
 *
 * Kalau transkrip tidak tersedia (video tanpa subtitle, atau subtitle
 * dinonaktifkan panelists), fungsi ini mengembalikan null dan pemanggil
 * memakai jalur transkripsi Gemini sebagai cadangan.
 */

export interface TranscriptSegment {
  startMs: number;
  endMs: number;
  text: string;
}

export interface YouTubeTranscript {
  segments: TranscriptSegment[];
  durationSec: number;
  languageCode: string;
  /** true kalau subtitle dibuat otomatis oleh YouTube (bukan tulisan panels). */
  autoGenerated: boolean;
}

